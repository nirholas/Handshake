import { chromium } from 'playwright';
const url = process.argv[2];
const watch = process.argv.slice(3);
const b = await chromium.launch({ args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1350, height: 940 } });
const reqs = [];
p.on('request', (r) => reqs.push(r.url()));
await p.goto(url, { waitUntil: 'load', timeout: 90000 });
await p.waitForTimeout(6000);
const atLoad = reqs.length;
console.log('--- at load+6s ---');
for (const w of watch) console.log(' ', reqs.some(u => u.includes(w)) ? 'LOADED  ' : 'deferred', w);
console.log('  total requests:', atLoad);
await p.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await p.waitForTimeout(6000);
console.log('--- after scrolling to bottom ---');
for (const w of watch) console.log(' ', reqs.some(u => u.includes(w)) ? 'LOADED  ' : 'MISSING ', w);
console.log('  total requests:', reqs.length);
await b.close();
