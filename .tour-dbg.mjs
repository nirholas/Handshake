import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import { chromium } from 'playwright';
const ROOT = '/workspaces/three.ws/tour-sdk';
const TYPES = { '.html':'text/html', '.js':'text/javascript', '.mjs':'text/javascript', '.json':'application/json', '.css':'text/css', '.map':'application/json' };
const server = createServer(async (req,res)=>{ const p = normalize(decodeURIComponent(req.url.split('?')[0])).replace(/^(\.\.[/\\])+/,''); try { const b = await readFile(join(ROOT,p)); res.writeHead(200,{'content-type':(TYPES[extname(p)]||'application/octet-stream')+'; charset=utf-8'}); res.end(b);} catch { res.writeHead(404).end('nf'); } });
await new Promise(r=>server.listen(4174,r));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport:{width:1440,height:900} });
page.on('console', m => console.log(`[console.${m.type()}]`, m.text()));
page.on('pageerror', e => console.log('[pageerror]', e.message));
page.on('requestfailed', r => console.log('[reqfail]', r.url().slice(0,120), r.failure()?.errorText));
await page.goto('http://localhost:4174/examples/shopify-storefront.html', { waitUntil:'load' });
await page.waitForFunction(()=>!!window.__featureTour,null,{timeout:15000});
await page.click('[data-tour-start]');
await page.waitForTimeout(12000);
console.log('state:', JSON.stringify(await page.evaluate(()=>({ active: window.__featureTour.isActive(), hasDirector: !!window.__featureTour.director, bar: !!document.querySelector('.tws-tour-bar'), canvas: !!document.querySelector('canvas'), twsNodes: [...document.querySelectorAll('[class*=tws-tour]')].map(n=>n.className).slice(0,10) }))));
await browser.close(); server.close();
